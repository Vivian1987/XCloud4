static SslPem ssl_pem_records[X4_CA_BUNDLE_COUNT];
static const SslPem *ssl_pem_ptrs[X4_CA_BUNDLE_COUNT];
static const SslPem *ssl_pem_ptrs_rsa[X4_CA_BUNDLE_RSA_COUNT];
static int ssl_pem_initialized = 0;

static void init_ssl_pem(void)
{
    if (ssl_pem_initialized) return;
    for (size_t i = 0; i < X4_CA_BUNDLE_COUNT; ++i) {
        ssl_pem_records[i].ptr = (char *)ca_entries[i].pem_data;
        ssl_pem_records[i].size = ca_entries[i].pem_size;
        ssl_pem_ptrs[i] = &ssl_pem_records[i];
    }
    /* 7 RSA roots for legacy firmware fallback: */
    /* [0] DigiCert Global Root G2 */
    /* [2] DigiCert Global Root CA */
    /* [3] Microsoft RSA Root Certificate Authority 2017 */
    /* [5] USERTrust RSA Certification Authority */
    /* [7] Baltimore CyberTrust Root */
    /* [8] DigiCert High Assurance EV Root CA */
    /* [10] Sectigo Public Server Authentication Root R46 */
    static const size_t rsa_indices[X4_CA_BUNDLE_RSA_COUNT] = {0, 2, 3, 5, 7, 8, 10};
    for (size_t i = 0; i < X4_CA_BUNDLE_RSA_COUNT; ++i) {
        ssl_pem_ptrs_rsa[i] = &ssl_pem_records[rsa_indices[i]];
    }
    ssl_pem_initialized = 1;
}

size_t x4_ca_bundle_count(void)
{
    return X4_CA_BUNDLE_COUNT;
}

size_t x4_ca_bundle_rsa_count(void)
{
    return X4_CA_BUNDLE_RSA_COUNT;
}

const X4CaCertEntry *x4_ca_bundle_entry(size_t index)
{
    if (index >= X4_CA_BUNDLE_COUNT) return NULL;
    return &ca_entries[index];
}

const SslPem * const *x4_ca_bundle_get_ssl_pem_ptrs(size_t *out_count)
{
    init_ssl_pem();
    if (out_count) *out_count = X4_CA_BUNDLE_COUNT;
    return ssl_pem_ptrs;
}

const SslPem * const *x4_ca_bundle_get_ssl_pem_ptrs_rsa(size_t *out_count)
{
    init_ssl_pem();
    if (out_count) *out_count = X4_CA_BUNDLE_RSA_COUNT;
    return ssl_pem_ptrs_rsa;
}
